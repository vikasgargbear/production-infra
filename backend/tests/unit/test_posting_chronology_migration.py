def _load(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _definition(sql: str, name: str) -> str:
    start = sql.index(
        f'CREATE OR REPLACE FUNCTION "erp_automation_commands"."{name}"('
    )
    body_start = sql.index("$function$", start) + len("$function$")
    end = sql.index("$function$", body_start)
    return sql[start:end]


def test_posting_chronology_migration_is_generator_owned_hash_bound_and_linear() -> None:
    generator = _load(GENERATOR, "posting_chronology_generator")
    revision = _load(REVISION_PATH, "posting_chronology_revision")
    sql = SQL_PATH.read_text(encoding="utf-8")

    assert generator.generate_sql() == sql
    assert revision.revision == "20260828_0038"
    assert revision.down_revision == "20260828_0037"
    assert revision.EXPECTED_SQL_SHA256 == hashlib.sha256(sql.encode()).hexdigest()
    assert sql.count("CREATE OR REPLACE FUNCTION") == 9
    assert sql.startswith(
        "-- Generated by backend/scripts/generate_posting_chronology_migration.py."
    )
    assert sql.rstrip().endswith("RESET ROLE;")


def test_actual_document_dates_use_the_authenticated_organization_clock() -> None:
    sql = SQL_PATH.read_text(encoding="utf-8")
    checks = {
        "resolve_sales_dispatch_prepare": "dispatch_date",
        "resolve_purchase_order_prepare": "order_date",
        "resolve_supplier_invoice_prepare": "invoice_date",
        "resolve_sales_invoice_prepare": "invoice_date",
        "resolve_sales_order_prepare": "order_date",
        "resolve_sales_return_prepare": "return_date",
        "resolve_purchase_return_prepare": "return_date",
        "resolve_adjustment_note_prepare_unchecked_v0013": "note_date",
    }
    business_clock = '"erp_core_commands"."current_organization_business_date"()'
    for name, date_field in checks.items():
        definition = _definition(sql, name)
        activation = definition.index(
            "erp_security.activate_context(auth_user_id,organization_id)"
        )
        chronology = definition.index(f"{date_field}>{business_clock}")
        assert activation < chronology

    supplier = _definition(sql, "resolve_supplier_invoice_prepare")
    assert f"received_date>{business_clock}" in supplier
    assert "expected_on>" + business_clock not in sql
    assert "requested_delivery_date>" + business_clock not in sql
    assert "CURRENT_DATE" not in sql
    assert "Asia/Kolkata" not in sql


def test_predecessor_dates_are_locked_rejected_and_bound_to_source_versions() -> None:
    sql = SQL_PATH.read_text(encoding="utf-8")
    dispatch = _definition(sql, "resolve_sales_invoice_prepare")
    receipt = _definition(sql, "resolve_goods_receipt_prepare")
    supplier = _definition(sql, "resolve_supplier_invoice_prepare")
    purchase_return = _definition(sql, "resolve_purchase_return_prepare")

    for fragment in (
        "invoice_date<dispatch_header.dispatch_date",
        "'dispatch_date',dispatch_header.dispatch_date",
        "'dispatch_row_version',dispatch_header.row_version",
        "FOR SHARE",
    ):
        assert fragment in dispatch
    for fragment in (
        "received_day<purchase_order.order_date",
        "'order_date',purchase_order.order_date",
    ):
        assert fragment in receipt
    for fragment in (
        "receipt_business_date:=(receipt.received_at AT TIME ZONE organization.timezone)::date",
        "received_date<receipt_business_date",
        "'goods_receipt_received_at',receipt.received_at",
        "'goods_receipt_business_date',receipt_business_date",
        "'received_at',receipt.received_at,'business_date',receipt_business_date",
    ):
        assert fragment in supplier
    assert "invoice_date<receipt_business_date" not in supplier
    assert "received_date<invoice_date" in supplier
    for fragment in (
        "portal_line.invoice_date>return_date",
        "'invoice_date',portal_line.invoice_date",
        "'supplier_invoice_date',invoice.supplier_invoice_date",
    ):
        assert fragment in purchase_return


