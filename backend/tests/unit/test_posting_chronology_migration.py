ROOT = Path(__file__).parents[3]
GENERATOR = ROOT / "backend/scripts/generate_posting_chronology_migration.py"
SQL_PATH = ROOT / "backend/alembic/sql/20260828_0038_posting_chronology.sql"
REVISION_PATH = ROOT / "backend/alembic/versions/20260828_0038_posting_chronology.py"
